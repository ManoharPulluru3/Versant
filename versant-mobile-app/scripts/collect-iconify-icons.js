/**
 * Scans the project for Iconify icon ids (e.g. mdi:home), builds a static bundle,
 * and writes src/generated/iconify-bundle.js.
 */
const fs = require('fs')
const path = require('path')
const crypto = require('crypto')

const ROOT = path.join(__dirname, '..')
const SRC_DIR = path.join(ROOT, 'src')
const GENERATED_DIR = path.join(SRC_DIR, 'generated')
const BUNDLE_FILE = path.join(GENERATED_DIR, 'iconify-bundle.js')
const ICONIFY_INIT = path.join(SRC_DIR, 'iconify-init.js')
const GENERATED_JSON = path.join(ROOT, 'iconify.icons.generated.json')
const ICON_RE =
  /(?:mdi|solar|lucide|codicon|hugeicons|fluent|logos|devicon|skill-icons):[a-z0-9-]+/g

function walk(dir, files = []) {
  if (!fs.existsSync(dir)) {
    return files
  }
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory() && entry.name !== 'generated') {
      walk(full, files)
    } else if (/\.(jsx?|tsx?)$/.test(entry.name)) {
      files.push(full)
    }
  }
  return files
}

function readExtras() {
  const extrasPath = path.join(ROOT, 'iconify.extras.js')
  if (!fs.existsSync(extrasPath)) {
    return []
  }
  const extras = require(extrasPath)
  return Array.isArray(extras) ? extras : []
}

function scanFile(file, icons) {
  const text = fs.readFileSync(file, 'utf8')
  for (const match of text.matchAll(ICON_RE)) {
    icons.add(match[0])
  }
}

function collectIcons() {
  const icons = new Set(readExtras())
  const files = walk(SRC_DIR)

  for (const extra of ['App.jsx', 'App.tsx', 'index.js']) {
    const full = path.join(ROOT, extra)
    if (fs.existsSync(full)) {
      files.push(full)
    }
  }

  for (const file of files) {
    scanFile(file, icons)
  }

  return [...icons].sort()
}

function iconsHash(icons) {
  return crypto.createHash('sha256').update(icons.join('\n')).digest('hex').slice(0, 12)
}

function buildBundleCode(icons) {
  const babel = require('@babel/core')
  const stub = '// @@iconify-code-gen\n'
  const filename = path.join(ROOT, '__iconify_codegen__.js')

  const { code } = babel.transformSync(stub, {
    filename,
    babelrc: false,
    configFile: false,
    plugins: [[require.resolve('react-native-iconify/babel'), { icons }]],
  })

  if (!code.includes('globalThis.__ICONIFY__')) {
    throw new Error('Icon bundle generation failed — babel plugin produced no icon data')
  }

  for (const icon of icons) {
    if (!code.includes(JSON.stringify(icon))) {
      throw new Error(`Icon bundle missing "${icon}" — check icon name on icones.js.org`)
    }
  }

  return code
}

function extractIconMapJson(code) {
  const match = code.match(
    /globalThis\.__ICONIFY__\s*=\s*(\{[\s\S]*\});?\s*globalThis\.__ICONIFY_PLUGIN_LOADED__/,
  )
  if (!match) {
    throw new Error('Icon bundle generation failed — could not extract icon map')
  }
  return match[1]
}

function writeIconifyInit() {
  const content = `// Re-export icon map (see scripts/sync-iconify-icons.js).
export {ICONIFY_ICONS} from './generated/iconify-bundle';
`
  fs.writeFileSync(ICONIFY_INIT, content, 'utf8')
}

function writeBundle(icons) {
  const hash = iconsHash(icons)
  const raw = buildBundleCode(icons)
  const mapJson = extractIconMapJson(raw)
  const header = `// Auto-generated by scripts/sync-iconify-icons.js — do not edit.
// icons: ${icons.length} | hash: ${hash}

export const ICONIFY_ICONS = ${mapJson};
`
  fs.mkdirSync(GENERATED_DIR, { recursive: true })
  fs.writeFileSync(BUNDLE_FILE, header, 'utf8')
  fs.writeFileSync(
    GENERATED_JSON,
    `${JSON.stringify({ hash, count: icons.length, icons }, null, 2)}\n`,
    'utf8',
  )
  writeIconifyInit()
  return hash
}

function syncIcons({ quiet = false } = {}) {
  const icons = collectIcons()
  const hash = writeBundle(icons)
  if (!quiet) {
    process.stdout.write(`Iconify: ${icons.length} icons bundled (hash ${hash})\n`)
  }
  return icons
}

module.exports = { collectIcons, syncIcons, iconsHash, ROOT, SRC_DIR }

if (require.main === module) {
  try {
    syncIcons()
  } catch (err) {
    process.stderr.write(`Iconify sync failed: ${err.message}\n`)
    process.exit(1)
  }
}
